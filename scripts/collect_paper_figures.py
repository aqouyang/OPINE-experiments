def recon_rank(prov):
    for k in ("representative_stored_rank", "representative_dof"):
        if k in prov:
            return int(prov[k])
    return None


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default=os.path.join(REPO, "paper_figures"))
    a = ap.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)

    def copy_one(name, stem, exts, prov_path):
        src = os.path.join(REPO, stem)
        pj = os.path.join(REPO, prov_path)
        if not os.path.exists(pj):
            raise SystemExit(f"missing provenance: {pj}")
        copied = []
        for ext in exts:
            s = f"{src}.{ext}"
            if not os.path.exists(s):
                raise SystemExit(f"missing figure: {s}")
            d = os.path.join(a.out_dir, f"{name}.{ext}")
            shutil.copy2(s, d)
            copied.append(os.path.basename(d))
            print("copied", os.path.relpath(d, REPO))
        return {"name": name, "source_stem": stem,
                "source_mtime": os.path.getmtime(f"{src}.png"),
                "source_png_sha256": sha(f"{src}.png"),
                "provenance_source": prov_path, "files": copied}

    manifest = []
    for label, stem in SOURCES:
        prov = json.load(open(os.path.join(REPO, f"{stem}_provenance.json")))
        D = recon_rank(prov)
        name = f"summary_{label}" + (f"_D{D}" if D is not None else "")
        e = copy_one(name, stem, EXTS, f"{stem}_provenance.json")
        e.update(dataset=label, recon_plotted_D=D,
                 snapshot=prov.get("snapshot"))
        manifest.append(e)

    for x in EXTRAS:
        e = copy_one(x["name"], x["stem"], x["exts"], x["provenance"])
        prov = json.load(open(os.path.join(REPO, x["provenance"])))
        # "dof" is the stored rank in some provenance files and the
        # retained dimension in others; retained_D is authoritative where it
        # exists, otherwise fall back to the CNN's stored rank, which is the
        # retained dimension by definition.
        ret = prov.get("retained_D") or {}
        sr = prov.get("stored_rank") or {}
        plotted = (ret.get("CNN") or ret.get("cnn")
                   or sr.get("CNN") or sr.get("cnn") or prov.get("dof"))
        e.update(dataset=x["dataset"], recon_plotted_D=plotted,
                 recon_stored_rank=prov.get("stored_rank"),
                 snapshot=prov.get("snapshot_index"), note=x["note"])
        manifest.append(e)

    keep = {"MANIFEST.json", "README.md"}
    keep.update(f for m in manifest for f in m["files"])
    for f in sorted(os.listdir(a.out_dir)):
        if f not in keep and os.path.isfile(os.path.join(a.out_dir, f)):
            os.remove(os.path.join(a.out_dir, f))
            print("removed", f)

    man = os.path.join(a.out_dir, "MANIFEST.json")
    json.dump({"_what": "png copies of the paper's figures; the source next "
                        "to each experiment is authoritative, re-run "
                        "scripts/collect_paper_figures.py after regenerating "
                        "one",
               "_formats": "png only here; the pdf / svg live at "
                           "source_stem next to the experiment",
               "figures": manifest}, open(man, "w"), indent=1)
    print("wrote", os.path.relpath(man, REPO))

    lines = ["# paper_figures",
             "",
             "Flat **png** copies of the paper's figures -- the summary "
             "figure of every dataset plus the few others the paper uses -- "
             "so they are in one place.  **Not** the source of truth: each "
             "figure is rendered next to its experiment and copied here by "
             "`scripts/collect_paper_figures.py`.  The pdf / svg stay at the "
             "source path in the table below.  Re-run that script after "
             "regenerating any figure; it also deletes anything else it "
             "finds here.",
             "",
             "The `D` column is the retained REAL dimension, the same one "
             "the summary curves plot: the real rank for POD and OPINE, the "
             "latent width for the CNN.  Nothing is halved -- the earlier "
             "D = stored rank / 2 mode-pair convention is withdrawn.",
             "",
             "| file | dataset | retained D | rendered from |",
             "|---|---|---|---|"]
    for m in manifest:
        lines.append(f"| `{m['name']}.png` | {m['dataset']} | "
                     f"{m['recon_plotted_D']} | `{m['source_stem']}.png` |")
    lines.append("")
    for m in manifest:
        if m.get("note"):
            lines += [f"`{m['name']}` — {m['note']}", ""]
    open(os.path.join(a.out_dir, "README.md"), "w").write("\n".join(lines))
    print("wrote", os.path.relpath(os.path.join(a.out_dir, "README.md"), REPO))


if __name__ == "__main__":
    main()
